#!/usr/bin/env python3
"""python3 tools/build-ground-art.py
Slices two of the user's sheets:
  art-production/ground-rings-frames-6x4.webp  → assets/ui/ground/{ring-ally,ring-foe,cell-frames,cell-corners}.webp   (horizontal strips, 6 frames / 6 colours each)
        row 1 green ring (ally) · row 2 red ring (foe) · row 3 cell frames: green red yellow blue grey orange · row 4 corner chevrons (6-frame glow)
  art-production/facing-arrows-4.png           → assets/ui/arrows/face-{ne,se,sw,nw}.webp
and writes js/ground-art.js (frame sizes + a tiny drawing helper: GroundArt.ring / frame / corners) so the battle draws them to fit the grid cell."""
import os, numpy as np
from PIL import Image
def runs(v, gap=6):
    out = []; s = None; g = 0; e = 0
    for i, x in enumerate(v):
        if x:
            if s is None: s = i
            g = 0; e = i
        elif s is not None:
            g += 1
            if g >= gap: out.append((s, e + 1)); s = None
    if s is not None: out.append((s, e + 1))
    return out
im = Image.open('art-production/ground-rings-frames-6x4.webp').convert('RGBA'); a = np.array(im)[:, :, 3] > 30
rows = runs(a.any(1)); assert len(rows) == 4
cols = [runs(a[y0:y1].any(0)) for (y0, y1) in rows[:3]]; assert all(len(c) == 6 for c in cols)
centers = [(c[0] + c[1]) / 2 for c in cols[0]]
os.makedirs('assets/ui/ground', exist_ok=True); os.makedirs('assets/ui/arrows', exist_ok=True)
def strip(name, pieces, cw, ch):
    s = Image.new('RGBA', (cw * 6, ch), (0, 0, 0, 0))
    for i, p in enumerate(pieces): s.paste(p, (i * cw + (cw - p.width) // 2, (ch - p.height) // 2), p)
    s.save('assets/ui/ground/%s.webp' % name, lossless=True, quality=100, method=6)
def pieces_of(ri):
    y0, y1 = rows[ri]; out = []
    for (x0, x1) in cols[ri]:
        sub = a[y0:y1, x0:x1]; ys = np.where(sub.any(1))[0]; out.append(im.crop((x0, y0 + ys[0], x1, y0 + ys[-1] + 1)))
    return out
RW, RH = 176, 108; FW, FH = 180, 112
strip('ring-ally', pieces_of(0), RW, RH); strip('ring-foe', pieces_of(1), RW, RH); strip('cell-frames', pieces_of(2), FW, FH)
# chevrons: group the pieces of row 4 by the nearest ring column, crop that column's whole box
y0, y1 = rows[3]; ch = []
for ci, cx in enumerate(centers):
    x0, x1 = int(cx - 95), int(cx + 95); sub = a[y0:y1, max(0, x0):x1]; xs = np.where(sub.any(0))[0]; ys = np.where(sub.any(1))[0]
    box = (max(0, x0) + xs[0], y0 + ys[0], max(0, x0) + xs[-1] + 1, y0 + ys[-1] + 1); ch.append(im.crop(box))
strip('cell-corners', ch, FW, FH)
# facing arrows
ar = Image.open('art-production/facing-arrows-4.png').convert('RGBA'); aa = np.array(ar)[:, :, 3] > 30
for name, (r0, r1) in zip(['ne', 'se', 'sw', 'nw'], runs(aa.any(1), 20)):
    xs = np.where(aa[r0:r1].any(0))[0]; piece = ar.crop((xs[0], r0, xs[-1] + 1, r1)); cv = Image.new('RGBA', (192, 160), (0, 0, 0, 0))
    cv.paste(piece, ((192 - piece.width) // 2, (160 - piece.height) // 2), piece); cv.save('assets/ui/arrows/face-%s.webp' % name, lossless=True, quality=100, method=6)
open('js/ground-art.js', 'w', encoding='utf8').write('''/* generated by tools/build-ground-art.py — do not edit by hand.
   The user's picture set for the battle ground: a ring under the active / targeted fighter (6-frame glow, green = team, red = foe), a frame for a cell
   (green red yellow blue grey orange) and glowing corner chevrons (6 frames). Everything is drawn to FIT the grid cell, so the caller passes the cell's size in world px.
   GroundArt.ring(g, foe, x, y, w, t)   centre x,y · width w (the picture keeps its own aspect)
   GroundArt.frame(g, name, x, y, w, h) name: green red yellow blue grey orange · fitted to w × h (a cell = 2·HW × 2·HH)
   GroundArt.corners(g, x, y, w, h, t)  animated glow, same fitting */
(function (root) {
  'use strict';
  const RING = { w: 176, h: 108, n: 6 }, CELL = { w: 180, h: 112, n: 6 }, IMG = {}, COL = ['green', 'red', 'yellow', 'blue', 'grey', 'orange'];
  const img = s => { let i = IMG[s]; if (!i) { i = IMG[s] = new Image(); i.src = s } return i.complete && i.naturalWidth ? i : null };
  root.GroundArt = {
    COL,
    ring(g, foe, x, y, w, t) { const i = img('assets/ui/ground/ring-' + (foe ? 'foe' : 'ally') + '.webp'); if (!i) return false; const f = Math.floor(t / 110) % RING.n, h = w * RING.h / RING.w; g.drawImage(i, f * RING.w, 0, RING.w, RING.h, x - w / 2, y - h / 2, w, h); return true },
    frame(g, name, x, y, w, h) { const i = img('assets/ui/ground/cell-frames.webp'), k = COL.indexOf(name); if (!i || k < 0) return false; g.drawImage(i, k * CELL.w, 0, CELL.w, CELL.h, x - w / 2, y - h / 2, w, h); return true },
    corners(g, x, y, w, h, t) { const i = img('assets/ui/ground/cell-corners.webp'); if (!i) return false; const f = Math.floor(t / 110) % CELL.n; g.drawImage(i, f * CELL.w, 0, CELL.w, CELL.h, x - w / 2, y - h / 2, w, h); return true }
  };
})(globalThis);
''')
print('ok', RW, RH, FW, FH)
