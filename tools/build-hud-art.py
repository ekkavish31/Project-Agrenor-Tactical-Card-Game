#!/usr/bin/env python3
"""python3 tools/build-hud-art.py [sheet.webp]   (default: art-production/hud-sheet-8x4.webp)
Slices the user's HUD object sheet (8 columns × 4 rows, transparent background, 32 pieces) into assets/ui/hud/<name>.webp
and writes css/hud-art.css (one class per button: normal · hover · pressed · disabled) so the game, the editors and any page use the SAME pictures.
Pieces are found by the transparent gaps between them, so the sheet does not need an even grid. Buttons are centred on a 192×192 canvas, the compass pieces on 240×240."""
import sys, os
import numpy as np
from PIL import Image
SRC = sys.argv[1] if len(sys.argv) > 1 else 'art-production/hud-sheet-8x4.webp'
im = Image.open(SRC).convert('RGBA'); a = np.array(im)[:, :, 3] > 30
def runs(v, gap=4):
    out = []; s = None; g = 0; e = 0
    for i, x in enumerate(v):
        if x:
            if s is None: s = i
            g = 0; e = i
        elif s is not None:
            g += 1
            if g >= gap: out.append((s, e + 1)); s = None
    if s is not None: out.append((s, e + 1))
    return out
boxes = []
for (y0, y1) in runs(a.any(1)):
    for (x0, x1) in runs(a[y0:y1].any(0)):
        ys = np.where(a[y0:y1, x0:x1].any(1))[0]; boxes.append((x0, y0 + ys[0], x1, y0 + ys[-1] + 1))
assert len(boxes) == 32, 'expected 32 pieces, found %d' % len(boxes)
NAMES = [
 'compass-frame', 'compass-rose', 'compass', 'compass-glow', 'rot-left', 'rot-left-hover', 'rot-right', 'rot-right-hover',
 'plus', 'plus-hover', 'minus', 'minus-hover', 'focus', 'focus-hover', 'expand', 'expand-hover',
 'plus-pressed', 'plus-disabled', 'minus-pressed', 'minus-disabled', 'focus-pressed', 'focus-disabled', 'expand-pressed', 'expand-disabled',
 'rot-left-pressed', 'rot-left-disabled', 'rot-right-pressed', 'rot-right-disabled', 'check', 'check-hover', 'x', 'x-hover']
os.makedirs('assets/ui/hud', exist_ok=True)
for name, b in zip(NAMES, boxes):
    piece = im.crop(b); S = 240 if name.startswith('compass') else 192
    canvas = Image.new('RGBA', (S, S), (0, 0, 0, 0)); canvas.paste(piece, ((S - piece.width) // 2, (S - piece.height) // 2), piece)
    canvas.save('assets/ui/hud/%s.webp' % name, lossless=True, quality=100, method=6)
BUT = ['rot-left', 'rot-right', 'plus', 'minus', 'focus', 'expand', 'check', 'x']
css = ['/* generated by tools/build-hud-art.py from art-production/hud-sheet-8x4.webp — do not edit by hand.',
       '   <button class="hudb hudb-plus"></button> : size with --s (default 56px) · states: normal, :hover, :active (pressed), :disabled. check / x have no pressed or disabled art (a tiny scale is used). */',
       '.hudb{--s:56px;width:var(--s);height:var(--s);border:0;padding:0;background:center/contain no-repeat;cursor:pointer;filter:drop-shadow(0 3px 5px #000a);transition:transform .1s,filter .1s;-webkit-tap-highlight-color:transparent}',
       '.hudb:hover{filter:drop-shadow(0 0 8px #ffd978) brightness(1.08)}.hudb:active{transform:scale(.95)}.hudb:disabled{cursor:default;filter:none;opacity:1;transform:none}']
for n in BUT:
    def f(s): return "url('../assets/ui/hud/%s.webp')" % s
    has = lambda s: os.path.exists('assets/ui/hud/%s.webp' % s)
    css.append('.hudb-%s{background-image:%s}' % (n, f(n)))
    if has(n + '-hover'): css.append('.hudb-%s:hover{background-image:%s}' % (n, f(n + '-hover')))
    if has(n + '-pressed'): css.append('.hudb-%s:active{background-image:%s}' % (n, f(n + '-pressed')))
    if has(n + '-disabled'): css.append('.hudb-%s:disabled,.hudb-%s:disabled:hover{background-image:%s}' % (n, n, f(n + '-disabled')))
open('css/hud-art.css', 'w', encoding='utf8').write('\n'.join(css) + '\n')
print('sliced', len(NAMES), 'pieces → assets/ui/hud/ · css/hud-art.css')
