#!/usr/bin/env python3
"""Apply per-animation ZIPs exported by Asset Studio (anim-*.zip) to the game folder.

Usage (run from the game folder):  python tools/apply-asset-patch.py anim-a.zip anim-b.zip ...
ZIPs are applied in the order given. Each one copies its images into the game and merges its
data/asset-patches/*.json into data/asset-manifest.json, then js/asset-manifest.js is rebuilt.
Old-style full ZIPs (asset-drop-*.zip, with a whole manifest) are refused: unpack those by hand.
"""
import json, sys, zipfile
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent
MANIFEST_JSON = ROOT / 'data' / 'asset-manifest.json'
MANIFEST_JS = ROOT / 'js' / 'asset-manifest.js'
JS_HEAD = '/* Generated by tools/build-asset-manifest.py and Asset Studio — the list of every game image. */\nwindow.ASSET_MANIFEST='
SKIP = {'ASSET-DROP-README.txt', 'data/asset-manifest.json', 'js/asset-manifest.js'}


def asset_keys(assets):
    seen, out = {}, []
    for a in assets:
        k = f"{a.get('id')}|{a.get('file')}"
        seen[k] = seen.get(k, 0) + 1
        out.append(f"{k}#{seen[k] - 1}")
    return out


def apply_patch(m, p):
    if p.get('format') != 'project-a-asset-patch':
        raise ValueError('not an asset patch')
    removed = set(p.get('removedAssets') or [])
    if removed:
        m['assets'] = [a for a, k in zip(m['assets'], asset_keys(m['assets'])) if k not in removed]
    index = {k: i for i, k in enumerate(asset_keys(m['assets']))}
    for item in p.get('assets') or []:
        i = index.get(item['key'])
        if i is None:
            m['assets'].append(item['entry'])
            index = {k: i for i, k in enumerate(asset_keys(m['assets']))}
        else:
            m['assets'][i] = item['entry']
    for name, s in (p.get('sections') or {}).items():
        sec = m.get(name)
        if not isinstance(sec, dict):
            sec = m[name] = {}
        for k in s.get('del') or []:
            sec.pop(k, None)
        sec.update(s.get('set') or {})
    for name, v in (p.get('values') or {}).items():
        if v is None:
            m.pop(name, None)
        else:
            m[name] = v


def safe_target(name):
    p = PurePosixPath(name)
    if p.is_absolute() or '..' in p.parts or not p.parts:
        raise ValueError(f'unsafe path in ZIP: {name}')
    return ROOT.joinpath(*p.parts)


def main(paths):
    if not paths:
        print(__doc__)
        return 1
    m = json.loads(MANIFEST_JSON.read_text(encoding='utf-8'))
    for zp in paths:
        with zipfile.ZipFile(zp) as z:
            names = [n for n in z.namelist() if not n.endswith('/')]
            patches = sorted(n for n in names if n.startswith('data/asset-patches/') and n.endswith('.json'))
            if not patches:
                print(f'SKIP {zp}: no data/asset-patches/*.json (old full ZIP — unpack by hand)')
                continue
            copied = 0
            for n in names:
                if n in SKIP or n.startswith('data/asset-patches/'):
                    continue
                t = safe_target(n)
                t.parent.mkdir(parents=True, exist_ok=True)
                t.write_bytes(z.read(n))
                copied += 1
            for n in patches:
                p = json.loads(z.read(n).decode('utf-8'))
                apply_patch(m, p)
                print(f"OK {zp}: {p.get('label')} · {len(p.get('assets') or [])} asset entries · {copied} files")
    MANIFEST_JSON.write_text(json.dumps(m, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    MANIFEST_JS.write_text(JS_HEAD + json.dumps(m, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
