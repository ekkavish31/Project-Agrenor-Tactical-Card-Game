#!/usr/bin/env python3
"""v98.892 · the four 90° road bends (assets/village-town/ground/road-curves-source.webp, supplied by the owner) for the village roads.
   The pieces are drawn at a steeper angle than the game (edge slope 0.53–0.71 instead of 0.5) and not exactly alike, so each one gets its own
   affine map: the straight part of each arm is measured (top silhouette = curb tops, +H_FACE px to the ground; bottom silhouette = ground),
   then 1 cell along each arm (= the other arm's width / 4) is mapped onto the game's grid vectors and the meeting point of the two centre
   lines onto the bend corner V.  Output: road-curves.webp (the 4 pieces, untouched pixels) + js/road-curves-data.js (crop, V, matrix, usable arm length).
   Run: python3 tools/build-road-curves.py"""
from PIL import Image, ImageFilter
import numpy as np, json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'); G = os.path.join(ROOT, 'assets/village-town/ground/')
im = Image.open(G + 'road-curves-source.webp').convert('RGBA'); A = np.array(im).astype(float); AL = A[:, :, 3] > 30
H_FACE = 12
T = {'NW': (-28, -14), 'NE': (28, -14), 'SE': (28, 14), 'SW': (-28, 14)}          # game screen vector of one cell
DUV = {'NW': (-1, 0), 'NE': (0, -1), 'SE': (1, 0), 'SW': (0, 1)}
# piece bbox (x, y, w, h) · two arms: (direction away from the bend, x range of its straight part, y window)
PIECES = [((70, 18, 694, 480), [('NW', (200, 266), (0, 520)), ('NE', (560, 641), (0, 520))]),
          ((69, 528, 689, 483), [('SW', (200, 281), (520, 1024)), ('SE', (560, 631), (520, 1024))]),
          ((921, 18, 416, 480), [('NE', (1130, 1231), (0, 260)), ('SE', (1150, 1186), (260, 520))]),
          ((929, 528, 402, 483), [('NW', (1060, 1131), (520, 780)), ('SW', (1040, 1131), (780, 1024))])]
def lines(xr, yr):
    xs, top, bot = [], [], []
    for x in range(*xr):
        idx = np.nonzero(AL[yr[0]:yr[1], x])[0]
        if len(idx) < 20: continue
        xs.append(x); top.append(idx[0] + yr[0] + H_FACE); bot.append(idx[-1] + yr[0])
    pT = np.polyfit(xs, top, 1); pB = np.polyfit(xs, bot, 1); m = (pT[0] + pB[0]) / 2
    return m, pT[1] + (pT[0] - m) * np.mean(xs), pB[1] + (pB[0] - m) * np.mean(xs)    # common slope, two intercepts
out = {}; crops = []
for (bx, by, bw, bh), arms in PIECES:
    L = []
    for d, xr, yr in arms:
        m, cA, cB = lines(xr, yr); sx = np.sign(T[d][0]); L.append(dict(d=d, m=m, cA=cA, cB=cB, c=(cA + cB) / 2, dv=np.array([sx, sx * m])))
    a1, a2 = L
    def per_cell(arm, other):     # sprite vector of one cell along `arm` = distance along it between the other arm's ground lines / 4
        d = arm['dv']; lam = (other['cB'] - other['cA']) / (d[1] - other['m'] * d[0]); return d * abs(lam) / 4
    s1, s2 = per_cell(a1, a2), per_cell(a2, a1)
    S = np.array([s1, s2]).T; Tm = np.array([T[a1['d']], T[a2['d']]], float).T; M = Tm @ np.linalg.inv(S)
    xv = (a2['c'] - a1['c']) / (a1['m'] - a2['m']); yv = a1['m'] * xv + a1['c']
    # usable straight length of each arm (cells): walk along the centre line until the picture ends
    def reach(arm, s):
        p = np.array([xv, yv]); n = 0.0
        while True:
            q = p + s * (n + .25)
            if not (0 <= q[0] < AL.shape[1] and 0 <= q[1] < AL.shape[0]) or not AL[int(q[1]), int(q[0])]: return n
            n += .25
    D = min(reach(a1, s1), reach(a2, s2)) - .6
    key = ','.join(sorted([a1['d'], a2['d']]))
    crops.append((key, im.crop((bx, by, bx + bw, by + bh)), xv - bx, yv - by, M, D))
    print(key, 'slopes', round(a1['m'], 3), round(a2['m'], 3), 'cells(px)', round(np.linalg.norm(s1), 1), round(np.linalg.norm(s2), 1), 'D', round(D, 2), 'M', np.round(M, 3).tolist())
W = max(c[1].width for c in crops); Hh = sum(c[1].height + 2 for c in crops); atlas = Image.new('RGBA', (W, Hh), (0, 0, 0, 0)); y = 0
for key, c, vx, vy, M, D in crops:
    rgb = c.convert('RGB').filter(ImageFilter.UnsharpMask(radius=1.2, percent=60, threshold=2)); c2 = Image.merge('RGBA', (*rgb.split(), c.split()[3]))
    atlas.paste(c2, (0, y)); out[key] = dict(x=0, y=y, w=c.width, h=c.height, vx=round(float(vx), 2), vy=round(float(vy + 0), 2), m=[round(float(v), 5) for v in M.flatten()], D=round(float(D), 2)); y += c.height + 2
atlas.save(G + 'road-curves.webp', quality=92)
open(os.path.join(ROOT, 'js/road-curves-data.js'), 'w').write('/* generated by tools/build-road-curves.py */\nwindow.ROAD_CURVES=' + json.dumps(out) + ';\n')
print('ok', atlas.size)
