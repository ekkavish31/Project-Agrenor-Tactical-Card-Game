/* v98.444 · node tools/build-studio-people.cjs  →  js/studio-people.js
   The roster the Asset Studio "Animation" tab must show, read from the GAME'S OWN data so a new villager / friend / monster cannot be forgotten:
     allies  = every friend with battle stats  (js/village-life.js ALLY_STATS: bram luna kier sigrid ren olwen nadia orla berg mil …)  → group "ตัวละคร"
     npcs    = every other person of js/village-life.js (the picture folder = look.sprite, else the id) + any folder of assets/village-town/npc/ nobody names → group "NPC ชาวบ้าน"
     (monsters / bosses come from js/studio-catalog.js STUDIO_ENEMIES — tools/test-studio-roster.cjs checks them against js/town-battle.js)
   tools/test-studio-roster.cjs fails when this file is stale. */
'use strict';
const fs = require('fs'), path = require('path'), ROOT = path.join(__dirname, '..');
function build() {
  const vl = fs.readFileSync(path.join(ROOT, 'js/village-life.js'), 'utf8'), people = {}, order = [];
  for (const m of vl.matchAll(/^\s*add\('([a-z0-9]+)',\s*\{\s*name:\s*'([^']+)'([^\n]*)/gm)) { const sp = m[3].match(/sprite:\s*'([a-z0-9]+)'/); people[m[1]] = { name: m[2], folder: sp ? sp[1] : m[1] }; order.push(m[1]) }
  const block = vl.slice(vl.indexOf('const ALLY_STATS')), end = block.indexOf('};'), allyKeys = [...block.slice(0, end).matchAll(/^\s*([a-z0-9]+):\s*\{\s*(?:name|get name)/gm)].map(m => m[1]).filter(k => k !== 'sib');
  const allyName = {}; for (const m of block.slice(0, end).matchAll(/^\s*([a-z0-9]+):\s*\{\s*name:\s*'([^']+)'/gm)) allyName[m[1]] = m[2];
  const dirs = fs.readdirSync(path.join(ROOT, 'assets/village-town/npc')).filter(d => fs.statSync(path.join(ROOT, 'assets/village-town/npc', d)).isDirectory());
  const allies = {}, npcs = {};
  for (const k of allyKeys) allies[k] = allyName[k] || people[k]?.name || k;
  for (const id of order) { const f = people[id].folder; if (allies[id] || allies[f] || npcs[f]) continue; if (dirs.includes(f)) npcs[f] = people[id].name }
  for (const d of dirs) if (!allies[d] && !npcs[d]) npcs[d] = d === 'mother' ? 'แม่' : d;   /* a picture folder nobody names yet still gets a row */
  return { allies, npcs };
}
module.exports = { build };
if (require.main === module) {
  const r = build();
  fs.writeFileSync(path.join(ROOT, 'js/studio-people.js'), '/* generated by tools/build-studio-people.cjs — the people of the game for Asset Studio › Animation (friends = "ตัวละคร", the rest = "NPC ชาวบ้าน") */\nwindow.STUDIO_PEOPLE=' + JSON.stringify(r) + ';\n');
  console.log('js/studio-people.js · friends ' + Object.keys(r.allies).length + ' · npcs ' + Object.keys(r.npcs).length);
}
