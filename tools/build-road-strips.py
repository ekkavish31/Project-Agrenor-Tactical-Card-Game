"""v98.885 · real 3D curb strips for the village roads, cut from the supplied road sheet.
Each straight piece of the sheet is warped (its 4 corners → the exact 2:1 grid) and the curb band of each of its two edges is cut out as 4-cell windows
(4 edge types: outward normal NW/SE = pieces A,C · NE/SW = piece B). Run: python3 tools/build-road-strips.py"""
from PIL import Image, ImageFilter
import numpy as np, math, json
import os
ROOT=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..')
SRC=os.path.join(ROOT,'assets/village-town/ground/road-sheet-source.webp')
spr=np.array(Image.open(SRC).convert('RGBA')).astype(float)
def sample(px,py):
    H,W=spr.shape[:2]; px=np.clip(px,0,W-1.001); py=np.clip(py,0,H-1.001); xi=px.astype(int); yi=py.astype(int); fx=(px-xi)[...,None]; fy=(py-yi)[...,None]
    # premultiplied bilinear
    def g(dy,dx): 
        v=spr[yi+dy,xi+dx].copy(); v[...,:3]*=v[...,3:4]/255; return v
    out=g(0,0)*(1-fx)*(1-fy)+g(0,1)*fx*(1-fy)+g(1,0)*(1-fx)*fy+g(1,1)*fx*fy
    a=out[...,3:4]; rgb=np.where(a>1e-3,out[...,:3]/np.maximum(a/255,1e-6),0); return np.concatenate([rgb,a],-1)
S=3
# tile defs: bbox origin, left corner (origin of s,t), e1 (along run, sprite px), e2 (across, sprite px, 4 cells)
TILES={
 'A':dict(o=(66,4),  left=(0,175),   e1=(316,-161),  e2=(98,55),   sv=(28,-14), tv=(28,14)),
 'C':dict(o=(1049,4),left=(0,192.5), e1=(382,-192.5),e2=(95.5,53.5),sv=(28,-14), tv=(28,14)),
 'B':dict(o=(564,4), left=(0,74.5),  e1=(279,146.5), e2=(100,-57.5),sv=(28,14),  tv=(28,-14)),
}
def render(tile,s0,Lw,t0,t1,flip_t=False,pad=0.0):
    d=TILES[tile]; sv=np.array(d['sv'],float); tv=np.array(d['tv'],float)
    # bbox of the band parallelogram in game px
    corners=[s*sv+t*tv for s in (0,Lw) for t in (t0,t1)]
    xs=[c[0] for c in corners]; ys=[c[1] for c in corners]; x0,x1,y0,y1=min(xs),max(xs),min(ys),max(ys)
    W=int(math.ceil((x1-x0)*S))+2; H=int(math.ceil((y1-y0)*S))+2
    gy,gx=np.mgrid[0:H,0:W]; wx=x0+gx/S; wy=y0+gy/S
    M=np.array([[sv[0],tv[0]],[sv[1],tv[1]]]); Mi=np.linalg.inv(M); st=np.einsum('ij,jyx->iyx',Mi,np.array([wx,wy]))
    s=st[0]; t=st[1]
    pxcell=abs(d['e2'][0])/4; Ls=abs(d['e1'][0])/pxcell
    sa=s0+s; sx=np.array(d['o'])[0]+d['left'][0]+sa/Ls*d['e1'][0]+t/4*d['e2'][0]; sy=np.array(d['o'])[1]+d['left'][1]+sa/Ls*d['e1'][1]+t/4*d['e2'][1]
    out=sample(sx,sy)
    inside=(s>=0)&(s<=Lw)&(t>=t0)&(t<=t1)
    # feather the t edges a little, hard cut on s (windows abut)
    out[...,3]*=inside
    return out,(x0,y0,W,H)

import json
S2=2   # px per world px in the atlas
S=S2
BANDS={'A_far':('A',-0.12,0.60),'A_near':('A',3.40,4.55),'B_near':('B',-0.58,0.50),'B_far':('B',3.42,4.15)}
# source windows (tile, s0): window length 4 cells
SRCS={'A':[('A',0),('A',4),('A',8),('C',0),('C',4),('C',8),('C',11)],'B':[('B',0),('B',4),('B',7)]}
atlas=[];meta={}
y=0; W=0; ims=[]
for typ,(axis,t0,t1) in BANDS.items():
    meta[typ]=[]
    for tile,s0 in SRCS[axis]:
        # for the C-tile the band offsets are the same (same orientation / same 4-cell width)
        o,(x0,y0,w,h)=render(tile,float(s0),4.0,t0,t1)
        im=Image.fromarray(np.clip(o,0,255).astype(np.uint8),'RGBA')
        # unsharp (the sprites are small and soft)
        rgb=im.convert('RGB').filter(ImageFilter.UnsharpMask(radius=1.6,percent=90,threshold=2)); im=Image.merge('RGBA',(*rgb.split(),im.split()[3]))
        ims.append((typ,tile,s0,im,x0,y0)); W=max(W,im.width)
H=sum(i[3].height+2 for i in ims)
atlas=Image.new('RGBA',(W,H),(0,0,0,0)); y=0
for typ,tile,s0,im,x0,y0 in ims:
    atlas.paste(im,(0,y)); meta[typ].append(dict(x=0,y=y,w=im.width,h=im.height,ox=round(-x0,3),oy=round(-y0,3))); y+=im.height+2
atlas.save(os.path.join(ROOT,'assets/village-town/ground/road-strips.webp'),quality=92); print(atlas.size, {k:len(v) for k,v in meta.items()})
data=dict(scale=S2,len=4,t={k:[BANDS[k][1],BANDS[k][2]] for k in BANDS},w=meta)
open(os.path.join(ROOT,'js/road-strips-data.js'),'w').write('/* generated by tools/build-road-strips.py */\nwindow.ROAD_STRIPS='+json.dumps(data)+';\n')
