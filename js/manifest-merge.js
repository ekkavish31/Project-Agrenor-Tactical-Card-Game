/* v98.136 · ASSET_MANIFEST merge — keeps a staged ("รอ Push") manifest from overwriting newer work on main.
   A manifest staged in this browser is a full copy made from what the studio saw THEN. If main got newer work afterwards (another browser, the editor, a commit from Claude),
   pushing that copy as it is would throw the newer work away, and the studio (which reads staged files first) shows the old state.
   merge(base, mine, theirs): base = the main manifest the staged copy was made from (null when unknown), mine = staged, theirs = main now.
     assets          by id: changed only on one side → that side · changed on both → mine · removed on one side and unchanged on the other → removed
     other sections  key by key, recursively; a leaf / array: changed on one side → that side, on both → mine
     without a base  nothing can count as removed: union — an asset only one side has is kept, an empty slot (status 'missing') takes the filled one,
                     and two versions of a saved set (objects with createdAt, e.g. a walk set) → the newer one */
(function (root) {
  'use strict';
  const J = x => JSON.stringify(x), same = (a, b) => J(a) === J(b), isObj = x => x && typeof x === 'object' && !Array.isArray(x);
  const newer = (m, t) => (isObj(m) && isObj(t) && m.createdAt && t.createdAt) ? (String(t.createdAt) > String(m.createdAt) ? t : m) : null;
  function mergeVal(b, m, t, hasBase) {
    if (m === undefined) return hasBase && b !== undefined && same(b, t) ? undefined : t;   // I removed it (and they did not change it) · or I never had it
    if (t === undefined) return hasBase && b !== undefined && same(b, m) ? undefined : m;
    if (same(m, t)) return m;
    const n = newer(m, t); if (n) return n;
    if (isObj(m) && isObj(t)) { const out = {}, keys = new Set([...Object.keys(t), ...Object.keys(m)]);
      for (const k of keys) { const v = mergeVal(isObj(b) ? b[k] : undefined, m[k], t[k], hasBase && isObj(b)); if (v !== undefined) out[k] = v } return out }
    if (hasBase) { if (same(b, m)) return t; if (same(b, t)) return m }
    return m;
  }
  const RANK = { missing: 0, planned: 1, unused: 1, code: 2, temp: 3, final: 4 };   /* how far along a picture is */
  function mergeAssets(b, m, t, hasBase) {
    const B = new Map((b || []).map(a => [a.id, a])), Mm = new Map((m || []).map(a => [a.id, a])), out = [], seen = new Set();
    const pick = (id, mm, tt) => { const bb = B.get(id);
      if (mm && tt) { if (same(mm, tt)) return mm; if (hasBase && bb) { if (same(bb, mm)) return tt; if (same(bb, tt)) return mm }
        if (!hasBase) {   /* v98.444 · no base: we cannot tell who changed what — keep the one that is further along, so an old staged copy cannot turn a finished picture back into code / temp (v98.421 lost 55 tutorial/card rows that way) */
          const r = x => RANK[x.status] ?? 2, rm = r(mm), rt = r(tt); if (rt !== rm) return rt > rm ? tt : mm;
          const v = x => String(x.artRevision || x.updatedAt || x.createdAt || ''); if (v(tt) > v(mm)) return tt }
        return mm }
      if (mm) return hasBase && bb && same(bb, mm) ? null : mm;   // they removed it, I did not touch it
      return hasBase && bb && same(bb, tt) ? null : tt };         // I removed it, they did not touch it
    for (const tt of t || []) { const a = pick(tt.id, Mm.get(tt.id), tt); seen.add(tt.id); if (a) out.push(a) }
    for (const mm of m || []) if (!seen.has(mm.id)) { const a = pick(mm.id, mm, undefined); if (a) out.push(a) }
    return out;
  }
  function merge(base, mine, theirs) {
    const hasBase = !!base, out = {}, keys = new Set([...Object.keys(theirs || {}), ...Object.keys(mine || {})]);
    for (const k of keys) {
      if (k === 'assets') { out.assets = mergeAssets(base && base.assets, mine.assets, theirs.assets, hasBase); continue }
      const v = mergeVal(base ? base[k] : undefined, mine[k], theirs[k], hasBase); if (v !== undefined) out[k] = v;
    }
    /* v98.444 · RETIRED pictures (manifest.retired = [file paths]) never come back: an old staged copy made before they were retired
       would otherwise bring them back through the union above (it happened with the old button-system pictures in v98.435) */
    const retired = [...new Set([...((theirs || {}).retired || []), ...((mine || {}).retired || [])])];
    if (retired.length) { const R = new Set(retired); out.retired = retired; if (Array.isArray(out.assets)) out.assets = out.assets.filter(a => !R.has(a.file)) }
    return out;
  }
  const HEAD = '/* Generated by tools/build-asset-manifest.py and Asset Studio — the list of every game image. */\nwindow.ASSET_MANIFEST=';
  const jsonText = m => JSON.stringify(m, null, 1) + '\n', jsText = m => HEAD + JSON.stringify(m) + ';\n';
  const parseJs = t => { const i = t.indexOf('window.ASSET_MANIFEST='); if (i < 0) return null; const s = t.slice(i + 22).trim().replace(/;\s*$/, ''); return JSON.parse(s) };
  /* files: [[path, Blob|string|null]] (staged list) · headText: main's data/asset-manifest.json now · baseText: what the staged copy was made from (or null)
     → { files, changed, note } with both manifest files rebuilt from the merge (only when the staged manifest is not already based on main now) */
  async function rebase(files, headText, baseText) {
    const P = 'data/asset-manifest.json', PJ = 'js/asset-manifest.js', i = files.findIndex(([p, b]) => p === P && b), ij = files.findIndex(([p, b]) => p === PJ && b);
    if (i < 0 && ij < 0) return { files, changed: false };
    const read = async b => typeof b === 'string' ? b : await b.text();
    let mine = null; try { mine = i >= 0 ? JSON.parse(await read(files[i][1])) : parseJs(await read(files[ij][1])) } catch (e) { return { files, changed: false, note: 'อ่าน manifest ที่รอ push ไม่ได้' } }
    let theirs = null; try { theirs = JSON.parse(headText) } catch (e) { return { files, changed: false } }
    if (same(mine, theirs)) return { files, changed: false };
    let base = null; try { base = baseText ? JSON.parse(baseText) : null } catch (e) { }
    if (base && same(base, theirs)) return { files, changed: false };   // main did not move since the copy was made: nothing to merge
    const merged = merge(base, mine, theirs), out = files.filter(([p]) => p !== P && p !== PJ);
    out.push([P, new Blob([jsonText(merged)], { type: 'application/json' })], [PJ, new Blob([jsText(merged)], { type: 'text/javascript' })]);
    return { files: out, changed: true, merged, note: (base ? 'รวมกับงานใหม่บน main (3 ทาง)' : 'รวมกับงานใหม่บน main (ไม่มีต้นฉบับ: รวมทั้งสองฝั่ง)') + ' · assets ' + (mine.assets || []).length + ' → ' + merged.assets.length };
  }
  root.ManifestMerge = { merge, rebase, jsonText, jsText };
  if (typeof module === 'object' && module.exports) module.exports = root.ManifestMerge;
})(typeof window !== 'undefined' ? window : globalThis);
